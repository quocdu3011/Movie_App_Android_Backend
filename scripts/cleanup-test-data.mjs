import 'dotenv/config';
import pg from 'pg';

const { Client } = pg;
const dryRun = process.argv.includes('--dry-run');
const adminUrl = process.env.POSTGRES_ADMIN_URL;
if (!adminUrl) throw new Error('POSTGRES_ADMIN_URL is required');

async function connect(name) {
  const url = new URL(adminUrl);
  url.pathname = `/${name}`;
  const client = new Client({ connectionString: url.toString() });
  await client.connect();
  return client;
}

async function remove(client, sql, values = []) {
  if (dryRun) return 0;
  return (await client.query(sql, values)).rowCount ?? 0;
}

const count = (client, sql, values = []) => client.query(sql, values).then((result) => Number(result.rows[0].count));

const auth = await connect('auth_db');
const profile = await connect('profile_db');
const catalog = await connect('catalog_db');
const payment = await connect('payment_db');
const streaming = await connect('streaming_db');
const notification = await connect('notification_db');
const recommendation = await connect('recommendation_db');
const worker = await connect('worker_db');
const clients = [auth, profile, catalog, payment, streaming, notification, recommendation, worker];

try {
  // `example.test` is reserved for testing; the remaining markers are generated by the E2E suites.
  const userRows = await auth.query(
    'SELECT id FROM users WHERE email LIKE $1 OR email LIKE $2',
    ['%@example.test', '%@admin-e2e.test'],
  );
  const userIds = userRows.rows.map((row) => row.id);
  const movieRows = await catalog.query(`
    SELECT DISTINCT m.id
    FROM movies m
    LEFT JOIN content_sources cs ON cs.movie_id=m.id
    WHERE m.title LIKE $1
       OR m.title=$2
       OR m.title LIKE $3
       OR m.title LIKE $4
       OR cs.provider IN ($5,$6)
       OR cs.external_id LIKE $7`,
  ['G5 Fixture %', 'G5 owned fixture', 'G6 %', 'G8 Action %', 'g7-fixture', 'g8-fixture', 'kk-g3-%']);
  const movieIds = movieRows.rows.map((row) => row.id);
  const profileRows = await profile.query('SELECT id FROM profiles WHERE user_id=ANY($1::uuid[])', [userIds]);
  const profileIds = profileRows.rows.map((row) => row.id);
  const sourceRows = await catalog.query('SELECT id FROM content_sources WHERE movie_id=ANY($1::uuid[])', [movieIds]);
  const sourceIds = sourceRows.rows.map((row) => row.id);
  const itemRows = await catalog.query('SELECT id FROM source_items WHERE movie_id=ANY($1::uuid[])', [movieIds]);
  const sourceItemIds = itemRows.rows.map((row) => row.id);
  const assetRows = await streaming.query('SELECT id FROM video_assets WHERE source_item_id=ANY($1::uuid[])', [sourceItemIds]);
  const assetIds = assetRows.rows.map((row) => row.id);
  const sessionRows = await streaming.query(
    'SELECT id FROM playback_sessions WHERE user_id=ANY($1::uuid[]) OR profile_id=ANY($2::uuid[]) OR movie_id=ANY($3::uuid[])',
    [userIds, profileIds, movieIds],
  );
  const sessionIds = sessionRows.rows.map((row) => row.id);
  const paymentRows = await payment.query('SELECT id FROM payments WHERE user_id=ANY($1::uuid[])', [userIds]);
  const paymentIds = paymentRows.rows.map((row) => row.id);
  const subscriptionRows = await payment.query('SELECT id FROM subscriptions WHERE user_id=ANY($1::uuid[])', [userIds]);
  const subscriptionIds = subscriptionRows.rows.map((row) => row.id);

  const before = {
    users: userIds.length,
    profiles: profileIds.length,
    movies: movieIds.length,
    sourceItems: sourceItemIds.length,
    videoAssets: assetIds.length,
    playbackSessions: sessionIds.length,
    payments: paymentIds.length,
    subscriptions: subscriptionIds.length,
    testPlans: await count(payment, 'SELECT count(*) FROM plans WHERE id LIKE $1 OR name LIKE $2', ['g4-test-%', 'Admin E2E %']),
  };
  if (dryRun) {
    console.log(JSON.stringify({ mode: 'dry-run', matched: before }, null, 2));
    process.exitCode = 0;
  } else {
    // Delete dependent records before their cross-service parents. Every database has its own transaction.
    await worker.query('BEGIN');
    await remove(worker, 'DELETE FROM worker_outbox WHERE aggregate_id=ANY($1::uuid[])', [assetIds]);
    await remove(worker, 'DELETE FROM transcode_jobs WHERE asset_id=ANY($1::uuid[]) OR source_item_id=ANY($2::uuid[])', [assetIds, sourceItemIds]);
    await worker.query('COMMIT');

    await notification.query('BEGIN');
    const notificationEvents = await notification.query(
      'DELETE FROM notification_deliveries WHERE recipient_id=ANY($1::text[]) OR recipient_id=$2 RETURNING event_id',
      [userIds.concat(profileIds), 'fail-recipient'],
    );
    await remove(notification, 'DELETE FROM notification_inbox_events WHERE event_id=ANY($1::uuid[])', [notificationEvents.rows.map((row) => row.event_id)]);
    await notification.query('COMMIT');

    await recommendation.query('BEGIN');
    const recommendationEvents = await recommendation.query(
      'DELETE FROM watch_events WHERE user_id=ANY($1::uuid[]) OR profile_id=ANY($2::uuid[]) OR movie_id=ANY($3::uuid[]) RETURNING event_id',
      [userIds, profileIds, movieIds],
    );
    await remove(recommendation, 'DELETE FROM processed_events WHERE event_id=ANY($1::uuid[])', [recommendationEvents.rows.map((row) => row.event_id)]);
    await recommendation.query('COMMIT');

    await streaming.query('BEGIN');
    await remove(streaming, 'DELETE FROM outbox_events WHERE aggregate_id=ANY($1::uuid[]) OR aggregate_id=ANY($2::uuid[])', [sessionIds, assetIds]);
    await remove(streaming, 'DELETE FROM watch_progress WHERE profile_id=ANY($1::uuid[]) OR movie_id=ANY($2::uuid[]) OR source_item_id=ANY($3::uuid[])', [profileIds, movieIds, sourceItemIds]);
    await remove(streaming, 'DELETE FROM video_assets WHERE id=ANY($1::uuid[])', [assetIds]);
    await remove(streaming, 'DELETE FROM playback_sessions WHERE id=ANY($1::uuid[])', [sessionIds]);
    await streaming.query('COMMIT');

    await payment.query('BEGIN');
    await remove(payment, 'DELETE FROM outbox_events WHERE aggregate_id=ANY($1::uuid[]) OR aggregate_id=ANY($2::uuid[])', [paymentIds, subscriptionIds]);
    await remove(payment, 'DELETE FROM payment_webhook_receipts WHERE payment_id=ANY($1::uuid[])', [paymentIds]);
    await remove(payment, 'DELETE FROM payment_requests WHERE payment_id=ANY($1::uuid[]) OR user_id=ANY($2::uuid[])', [paymentIds, userIds]);
    await remove(payment, 'DELETE FROM subscription_reminders WHERE subscription_id=ANY($1::uuid[])', [subscriptionIds]);
    await remove(payment, 'DELETE FROM payments WHERE id=ANY($1::uuid[])', [paymentIds]);
    await remove(payment, 'DELETE FROM subscriptions WHERE id=ANY($1::uuid[])', [subscriptionIds]);
    await remove(payment, 'DELETE FROM purchase_guards WHERE user_id=ANY($1::uuid[])', [userIds]);
    await remove(payment, 'DELETE FROM plans WHERE id LIKE $1 OR name LIKE $2', ['g4-test-%', 'Admin E2E %']);
    await payment.query('COMMIT');

    await profile.query('BEGIN');
    await remove(profile, 'DELETE FROM outbox_events WHERE aggregate_id=ANY($1::uuid[])', [profileIds]);
    await remove(profile, 'DELETE FROM profile_quotas WHERE user_id=ANY($1::uuid[])', [userIds]);
    await remove(profile, 'DELETE FROM profiles WHERE id=ANY($1::uuid[])', [profileIds]);
    await profile.query('COMMIT');

    await catalog.query('BEGIN');
    await remove(catalog, 'DELETE FROM outbox_events WHERE aggregate_id=ANY($1::uuid[]) OR aggregate_id=ANY($2::uuid[])', [movieIds, sourceIds]);
    await remove(catalog, 'DELETE FROM catalog_audit_logs WHERE actor_id=ANY($1::uuid[]) OR movie_id=ANY($2::uuid[]) OR source_item_id=ANY($3::uuid[])', [userIds, movieIds, sourceItemIds]);
    await remove(catalog, 'DELETE FROM search_inbox_events WHERE movie_id=ANY($1::uuid[])', [movieIds]);
    await remove(catalog, 'DELETE FROM search_projection_versions WHERE movie_id=ANY($1::uuid[])', [movieIds]);
    await remove(catalog, 'DELETE FROM sync_runs WHERE requested_by=ANY($1::uuid[])', [userIds]);
    await remove(catalog, 'DELETE FROM movies WHERE id=ANY($1::uuid[])', [movieIds]);
    await remove(catalog, 'DELETE FROM genres WHERE slug LIKE $1', ['g8-action-%']);
    await catalog.query('COMMIT');

    await auth.query('BEGIN');
    await remove(auth, 'DELETE FROM admin_audit_logs WHERE actor_id=ANY($1::uuid[]) OR target_user_id=ANY($1::uuid[])', [userIds]);
    await remove(auth, 'DELETE FROM users WHERE id=ANY($1::uuid[])', [userIds]);
    await remove(auth, 'DROP TABLE IF EXISTS g0_persistence_check');
    await auth.query('COMMIT');

    console.log(JSON.stringify({ mode: 'deleted', matched: before }, null, 2));
  }
} catch (error) {
  await Promise.all(clients.map((client) => client.query('ROLLBACK').catch(() => undefined)));
  throw error;
} finally {
  await Promise.all(clients.map((client) => client.end()));
}
